#requires -Version 7.4
<#
.SYNOPSIS
    Translates a C# fixture and checks the PowerShell against the original.
.DESCRIPTION
    Three steps: translate the fixture with ConvertFrom-CSharp; compile the
    same C# with Roslyn into build/ as a comparison only (never shipped);
    call both with the same inputs and report every difference. The naive
    PowerShell reading of the same expressions is shown alongside, to make
    the semantic traps visible.
#>
[CmdletBinding()]
param([string] $Fixture = (Join-Path $PSScriptRoot 'fixtures/ProgressLayout.cs'))
$ErrorActionPreference = 'Stop'
$root = Split-Path $PSScriptRoot
. (Join-Path $root 'src/ConvertFrom-CSharp.ps1')

$build = Join-Path $root 'build'
$null = New-Item -ItemType Directory -Force -Path $build

# 1. Translate.
$result = ConvertFrom-CSharp -Path $Fixture
$psFile = Join-Path $build 'ProgressLayout.generated.ps1'
$header = "# Generated by cs2ps from $(Split-Path $Fixture -Leaf), SHA-256 $((Get-FileHash $Fixture).Hash). Review before use.`n"
Set-Content -LiteralPath $psFile -Value ($header + $result.PowerShell) -NoNewline
"translated: $(Split-Path $psFile -Leaf), diagnostics: $($result.Diagnostics.Count)"
$result.Diagnostics | ForEach-Object { "  line $($_.Line): $($_.Message)" }

# 2. Compile the original with Roslyn, as a comparison only, and load it from its path.
$src = [IO.File]::ReadAllText($Fixture)
$tree = [Microsoft.CodeAnalysis.CSharp.CSharpSyntaxTree]::ParseText($src)
$runtimeDir = [IO.Path]::GetDirectoryName([object].Assembly.Location)
$refs = [Microsoft.CodeAnalysis.MetadataReference[]]@('System.Private.CoreLib.dll', 'System.Runtime.dll' | ForEach-Object { [Microsoft.CodeAnalysis.MetadataReference]::CreateFromFile((Join-Path $runtimeDir $_)) })
$opts = [Microsoft.CodeAnalysis.CSharp.CSharpCompilationOptions]::new([Microsoft.CodeAnalysis.OutputKind]::DynamicallyLinkedLibrary)
$dll = Join-Path $build "ProgressLayout.reference.$([Guid]::NewGuid().ToString('N')).dll"
$comp = [Microsoft.CodeAnalysis.CSharp.CSharpCompilation]::Create([IO.Path]::GetFileNameWithoutExtension($dll), [Microsoft.CodeAnalysis.SyntaxTree[]]@($tree), $refs, $opts)
$fs = [IO.File]::Create($dll)
try { $emit = $comp.Emit($fs) } finally { $fs.Dispose() }
if (-not $emit.Success) { throw "reference compile failed: $($emit.Diagnostics[0])" }
$type = [Reflection.Assembly]::LoadFrom($dll).GetType('ProgressLayout')

# 3. Compare on the same inputs.
. $psFile
$cases = @(
    @{ M = 'BarWidth'; F = 'Get-ProgressLayoutBarWidth'; A = @(-5, 80), @(0, 80), @(33, 80), @(57, 80), @(100, 80), @(150, 80), @(7, 3) }
    @{ M = 'FormatLabel'; F = 'Format-ProgressLayoutLabel'; A = @('Copying', 42), @('A very long activity name', 5) }
    @{ M = 'IsSame'; F = 'Test-ProgressLayoutSame'; A = @('a', 'A'), @('x', 'x') }
    @{ M = 'SumTo'; F = 'Get-ProgressLayoutSumTo'; A = @(0), @(1), @(10), @(100) }
    @{ M = 'Ratio'; F = 'Get-ProgressLayoutRatio'; A = @(1, 3), @(7, 2) }
    @{ M = 'Midpoint'; F = 'Get-ProgressLayoutMidpoint'; A = @(1.0, 2.0), @(2.0, 3.0), @(-3.0, 0.0) }
    @{ M = 'Clamp'; F = 'Get-ProgressLayoutClamp'; A = @(5, 0, 10), @(-1, 0, 10), @(11, 0, 10) }
)
$fail = 0; $calls = 0
foreach ($c in $cases) {
    $method = $type.GetMethod($c.M)
    $params = $method.GetParameters()
    foreach ($a in $c.A) {
        $calls++
        $expected = $method.Invoke($null, [object[]]$a)
        $splat = @{}; for ($i = 0; $i -lt $params.Count; $i++) { $splat[$params[$i].Name] = $a[$i] }
        $actual = & $c.F @splat
        $same = ($expected -is [string] -and $expected -ceq $actual) -or ($expected -isnot [string] -and $expected -eq $actual -and $expected.GetType() -eq $actual.GetType())
        if (-not $same) { $fail++ }
        "{0,-5} {1}({2}) = C# {3} | PowerShell {4}" -f $(if ($same) { 'ok' } else { 'DIFF' }), $c.M, ($a -join ', '), $expected, $actual
    }
}
"calls $calls, differences $fail"
"--- what a naive PowerShell reading gives for the integer-division case ---"
"  columns * percent / 100 with 80 and 57: C# 45, naive PowerShell $(80 * 57 / 100), naive [int] $([int](80 * 57 / 100))"
if ($fail) { exit 1 }
