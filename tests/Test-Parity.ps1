#requires -Version 7.4
[CmdletBinding()]
param([string] $Fixture)
$ErrorActionPreference = 'Stop'
$root = Split-Path $PSScriptRoot
. (Join-Path $root 'src/ConvertFrom-CSharp.ps1')
Initialize-Roslyn
$build = Join-Path $root 'build'
$null = New-Item -ItemType Directory -Force -Path $build
$fixtures = if ($Fixture) { @(Get-Item -LiteralPath $Fixture) } else { @(Get-ChildItem -LiteralPath (Join-Path $PSScriptRoot 'fixtures') -Filter '*.cs' | Sort-Object Name) }
$runtimeDir = [IO.Path]::GetDirectoryName([object].Assembly.Location)
$refs = [Microsoft.CodeAnalysis.MetadataReference[]]@('System.Private.CoreLib.dll','System.Runtime.dll','System.Collections.dll','System.Console.dll' | ForEach-Object { [Microsoft.CodeAnalysis.MetadataReference]::CreateFromFile((Join-Path $runtimeDir $_)) })
$opts = [Microsoft.CodeAnalysis.CSharp.CSharpCompilationOptions]::new([Microsoft.CodeAnalysis.OutputKind]::DynamicallyLinkedLibrary)

function Get-RootException($exception) {
    while ($exception.InnerException -and ($exception -is [Reflection.TargetInvocationException] -or $exception -is [System.Management.Automation.RuntimeException])) { $exception = $exception.InnerException }
    $exception.GetType().FullName
}
function Convert-InputValue($value, [type] $type) {
    if ($null -eq $value) { return $null }
    if ($type.IsByRef) { $type = $type.GetElementType() }
    if ($type.IsArray) {
        $array = [Array]::CreateInstance($type.GetElementType(), $value.Count)
        for ($i = 0; $i -lt $value.Count; $i++) { $array[$i] = Convert-InputValue $value[$i] $type.GetElementType() }
        return ,$array
    }
    if ($type.IsGenericType -and $type.GetGenericTypeDefinition() -eq [System.Collections.Generic.List``1]) {
        $list = [Activator]::CreateInstance($type)
        foreach ($item in $value) { $list.Add((Convert-InputValue $item $type.GetGenericArguments()[0])) }
        return ,$list
    }
    [System.Management.Automation.LanguagePrimitives]::ConvertTo($value, $type)
}
function Test-SameValue($expected, $actual) {
    if ($null -eq $expected) { return $null -eq $actual }
    if ($null -eq $actual) { return $false }
    if ($expected.GetType() -ne $actual.GetType()) { return $false }
    if ($expected -is [string]) { return [string]::Equals($expected, $actual, [StringComparison]::Ordinal) }
    if ($expected -is [array]) {
        if ($expected.Length -ne $actual.Length) { return $false }
        for ($i = 0; $i -lt $expected.Length; $i++) { if (-not (Test-SameValue $expected[$i] $actual[$i])) { return $false } }
        return $true
    }
    return $expected.Equals($actual)
}
$calls = 0; $differences = 0
foreach ($file in $fixtures) {
    $result = ConvertFrom-CSharp -Path $file.FullName
    if ($result.Diagnostics.Count) { throw "$($file.Name): translation diagnostics: $($result.Diagnostics | ConvertTo-Json -Compress)" }
    $psFile = Join-Path $build ($file.BaseName + '.generated.ps1')
    Set-Content -LiteralPath $psFile -Value ("# Generated by CS2PS; fixture SHA-256 $((Get-FileHash $file.FullName).Hash). Review before use.`n" + $result.PowerShell)
    $parseErrors = $null; $tokens = $null
    $null = [System.Management.Automation.Language.Parser]::ParseFile($psFile, [ref]$tokens, [ref]$parseErrors)
    if ($parseErrors.Count) { throw "$($file.Name): generated PowerShell parse error: $($parseErrors[0])" }
    $tree = [Microsoft.CodeAnalysis.CSharp.CSharpSyntaxTree]::ParseText([IO.File]::ReadAllText($file.FullName))
    $dll = Join-Path $build "$($file.BaseName).reference.$([Guid]::NewGuid().ToString('N')).dll"
    $comp = [Microsoft.CodeAnalysis.CSharp.CSharpCompilation]::Create([IO.Path]::GetFileNameWithoutExtension($dll), [Microsoft.CodeAnalysis.SyntaxTree[]]@($tree), $refs, $opts)
    $stream = [IO.File]::Create($dll)
    try { $emit = $comp.Emit($stream) } finally { $stream.Dispose() }
    if (-not $emit.Success) { throw "$($file.Name): reference compile failed: $($emit.Diagnostics[0])" }
    $assembly = [Reflection.Assembly]::LoadFrom($dll)
    . $psFile
    $casesFile = Join-Path $file.DirectoryName ($file.BaseName + '.cases.json')
    $cases = @(Get-Content -Raw -LiteralPath $casesFile | ConvertFrom-Json)
    $fixtureCalls = 0
    foreach ($case in $cases) {
        $type = $assembly.GetType($case.Type, $true)
        $method = $type.GetMethod($case.Method, [Reflection.BindingFlags]'Public,NonPublic,Static')
        if (-not $method) { throw "Missing test method: $($case.Type).$($case.Method)" }
        $mapping = @($result.Methods | Where-Object { $_.Type -ceq $case.Type -and $_.Method -ceq $case.Method })
        if ($mapping.Count -ne 1) { throw 'Ambiguous generated method mapping' }
        $parameters = $method.GetParameters()
        if ($case.Arguments.Count -ne $parameters.Count) { throw 'Incorrect parity argument count' }
        $argsCS = [object[]]::new($parameters.Count); $splat = @{}
        for ($i = 0; $i -lt $parameters.Count; $i++) {
            $argsCS[$i] = Convert-InputValue $case.Arguments[$i] $parameters[$i].ParameterType
            $splat[$mapping[0].Parameters[$i]] = Convert-InputValue $case.Arguments[$i] $parameters[$i].ParameterType
        }
        $expected = $null; $actual = $null; $csError = $null; $psError = $null
        $writerCS = [IO.StringWriter]::new(); $writerPS = [IO.StringWriter]::new()
        $originalOut = [Console]::Out
        try {
            [Console]::SetOut($writerCS)
            try { $expected = $method.Invoke($null, $argsCS) } catch { $csError = Get-RootException $_.Exception }
            [Console]::SetOut($writerPS)
            try { $actual = & $mapping[0].Function @splat } catch { $psError = Get-RootException $_.Exception }
        } finally { [Console]::SetOut($originalOut) }
        $same = (Test-SameValue $expected $actual) -and $csError -ceq $psError -and $writerCS.ToString() -ceq $writerPS.ToString()
        $writerCS.Dispose(); $writerPS.Dispose()
        $calls++; $fixtureCalls++
        if (-not $same) {
            $differences++
            "DIFF $($file.Name): $($case.Method) case $fixtureCalls; C#=$expected [$csError], PowerShell=$actual [$psError]"
        }
    }
    "$($file.Name): calls $fixtureCalls"
}
"calls $calls, differences $differences"
if ($differences) { exit 1 }
